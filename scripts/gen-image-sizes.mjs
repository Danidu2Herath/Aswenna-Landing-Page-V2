/**
 * Writes src/data/imageSizes.ts — the intrinsic size of every file in
 * public/images, read from the files themselves.
 *
 * Why it exists: an <img> with no width and height has no aspect ratio until
 * it downloads, so the browser reserves no space and everything below it
 * jumps when it arrives. That is cumulative layout shift, and it is one of
 * the three Core Web Vitals Google ranks on. Hard-coding the numbers in the
 * markup would rot the moment an image is replaced; reading them from disk
 * cannot drift.
 *
 *   node scripts/gen-image-sizes.mjs
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const base = join(root, "public/images");

/** Reads intrinsic size without decoding the whole file. */
function size(buf, file) {
  // PNG: IHDR is always first
  if (buf.readUInt32BE(0) === 0x89504e47) {
    return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  }
  // WebP: VP8 / VP8L / VP8X
  if (buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") {
    const fmt = buf.toString("ascii", 12, 16);
    if (fmt === "VP8X") return { w: (buf.readUIntLE(24, 3) & 0xffffff) + 1, h: (buf.readUIntLE(27, 3) & 0xffffff) + 1 };
    if (fmt === "VP8 ") return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
    if (fmt === "VP8L") {
      const b = buf.readUInt32LE(21);
      return { w: (b & 0x3fff) + 1, h: ((b >> 14) & 0x3fff) + 1 };
    }
  }
  // JPEG: walk the segments to SOF
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length) {
      if (buf[i] !== 0xff) { i++; continue; }
      const m = buf[i + 1];
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) {
        return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
      }
      i += 2 + buf.readUInt16BE(i + 2);
    }
  }
  // SVG: viewBox, else width/height attributes
  if (file.endsWith(".svg")) {
    const t = buf.toString("utf8", 0, 2000);
    const vb = /viewBox\s*=\s*["']\s*[\d.-]+\s+[\d.-]+\s+([\d.]+)\s+([\d.]+)/.exec(t);
    if (vb) return { w: Math.round(+vb[1]), h: Math.round(+vb[2]) };
    const w = /\bwidth\s*=\s*["']([\d.]+)/.exec(t);
    const h = /\bheight\s*=\s*["']([\d.]+)/.exec(t);
    if (w && h) return { w: Math.round(+w[1]), h: Math.round(+h[1]) };
  }
  return null;
}

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });

const out = {};
let skipped = [];
for (const file of walk(base).sort()) {
  if (file.endsWith("icons.svg")) continue; // the sprite is never an <img>
  const s = size(readFileSync(file), file);
  const url = "/" + relative(join(root, "public"), file).split(/[\\/]/).join("/");
  if (s) out[url] = [s.w, s.h];
  else skipped.push(url);
}

writeFileSync(
  join(root, "src/data/imageSizes.ts"),
  `/* GENERATED by scripts/gen-image-sizes.mjs — do not edit by hand.
   Intrinsic pixel sizes, read from the files in public/images. They are set
   on every <img> so the browser reserves the right space before the image
   arrives, instead of shifting the page when it does. */
export const imageSizes: Record<string, [number, number]> = ${JSON.stringify(out, null, 2)};

/** width/height props for an <img>, or nothing when the file is unknown. */
export function imgSize(src: string): { width: number; height: number } | Record<string, never> {
  const s = imageSizes[src];
  return s ? { width: s[0], height: s[1] } : {};
}
`,
);
console.log(`image-sizes: ${Object.keys(out).length} files` + (skipped.length ? `, skipped ${skipped.join(", ")}` : ""));
